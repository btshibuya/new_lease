export function defaultPolicies() {
  const p = {};
  for (const d of POLICIES) p[d.id] = d.default;
  return p;
}

export function policyById(id) {
  return POLICIES.find((p) => p.id === id);
}

/** 保存された方針を検証し、未知の値は既定値に戻す */
export function sanitizePolicies(saved) {
  const p = defaultPolicies();
  if (saved && typeof saved === 'object') {
    for (const d of POLICIES) {
      if (d.options.some((o) => o.value === saved[d.id])) p[d.id] = saved[d.id];
    }
  }
  return p;
}
